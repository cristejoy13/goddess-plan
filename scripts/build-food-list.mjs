// Builds api/_foods.js — the USDA food list the app downloads once and keeps
// on her gadget, so calories can be worked out even offline.
//
// Source: USDA FoodData Central, SR Legacy (April 2018, public domain, the
// final release — it will not change). Download and unzip it, then:
//   curl -LO https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip
//   unzip FoodData_Central_sr_legacy_food_csv_2018-04.zip
//   node scripts/build-food-list.mjs <unzipped folder>
//
// Each food becomes [description, kcal per 100 g, [[portion, grams], ...],
// [protein, carbs, fat per 100 g]] — a macro USDA does not list is null.
// Nothing is made up: a food without an energy value is left out.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('Give the unzipped SR Legacy folder.'); process.exit(1); }

// A small CSV reader: quoted fields, commas inside quotes, "" as a quote.
function readCsv(file) {
  const text = readFileSync(join(dir, file), 'utf8');
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i += 1; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows.filter(r => r.length > 1);
  return body.map(r => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

const units = Object.fromEntries(readCsv('measure_unit.csv').map(u => [u.id, u.name]));
const kcal = {};
const MACRO = { 1003: 0, 1005: 1, 1004: 2 }; // protein, carbs, fat
const macros = {};
for (const n of readCsv('food_nutrient.csv')) {
  if (n.nutrient_id === '1008') kcal[n.fdc_id] = Number(n.amount);
  else if (n.nutrient_id in MACRO) {
    const v = Number(n.amount);
    (macros[n.fdc_id] ||= [null, null, null])[MACRO[n.nutrient_id]] = Number.isFinite(v) ? Math.round(v * 10) / 10 : null;
  }
}
const portions = {};
for (const p of readCsv('food_portion.csv')) {
  const grams = Number(p.gram_weight);
  if (!(grams > 0)) continue;
  const unit = units[p.measure_unit_id];
  const label = [p.amount && p.amount !== '1' ? p.amount : '1', unit && unit !== 'undetermined' ? unit : '', p.modifier]
    .filter(Boolean).join(' ').replace(/\s+/g, ' ').trim().toLowerCase();
  (portions[p.fdc_id] ||= []).push([label, Math.round(grams * 10) / 10]);
}

const foods = readCsv('food.csv')
  .filter(f => Number.isFinite(kcal[f.fdc_id]))
  .map(f => [f.description, Math.round(kcal[f.fdc_id]), portions[f.fdc_id] || [], macros[f.fdc_id] || [null, null, null]]);

const out = `// Generated by scripts/build-food-list.mjs from USDA FoodData Central,
// SR Legacy (April 2018, public domain). Do not edit by hand.
// [description, kcal per 100 g, [[portion, grams], ...], [protein, carbs, fat per 100 g]]
export default ${JSON.stringify(foods)};
`;
writeFileSync(new URL('../api/_foods.js', import.meta.url), out);
console.log(`${foods.length} foods, ${(out.length / 1024).toFixed(0)} KB`);
